def render():
    ordered, visited, active = [], set(), set()
    def visit(name):
        if name in active:
            raise ValueError(f'Circular project import: {name}')
        if name in visited:
            return
        active.add(name)
        path = ROOT / (name.replace('.', '/') + '.lean')
        source = path.read_text(encoding='utf-8')
        for line in source.splitlines():
            if line.startswith('import '):
                for dependency in line.split()[1:]:
                    if dependency == 'RP3' or dependency.startswith('RP3.'):
                        visit(dependency)
        active.remove(name)
        visited.add(name)
        ordered.append((name, source))
    visit('RP3')
    external = sorted({dependency
        for _, source in ordered for line in source.splitlines()
        if line.startswith('import ') for dependency in line.split()[1:]
        if dependency != 'RP3' and not dependency.startswith('RP3.')})
    parts = [HEADER, ''.join('import '+name+'\n' for name in external), '\n']
    for number, (name, source) in enumerate(ordered):
        if name == 'RP3':
            continue
        body = '\n'.join(line for line in source.splitlines()
                         if not line.startswith('import '))
        parts.append(f'\n/- ===== {name.replace(".", "/")}.lean ===== -/\n'
                     f'section StandalonePart{number}\n{body}\nend StandalonePart{number}\n')
    return ''.join(parts), len(ordered)-1


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the existing bundle is stale')
    parser.add_argument('--output', type=Path, default=ROOT/'RP3-Formalization.lean')
    args = parser.parse_args()
    expected, count = render()
    if args.check:
        actual = args.output.read_text(encoding='utf-8') if args.output.exists() else ''
        if actual != expected:
            diff = difflib.unified_diff(actual.splitlines(), expected.splitlines(),
                                        fromfile=str(args.output), tofile='regenerated', n=2)
            print('\n'.join(list(diff)[:90]), file=sys.stderr)
            print('Standalone source is stale. Run python3 bundle_rp3.py.', file=sys.stderr)
            return 1
        print(f'Bundle synchronized: {count} modules, {len(expected.splitlines())} lines')
        return 0
    args.output.write_text(expected, encoding='utf-8')
    print(f'{args.output.name}: {count} modules, {len(expected.splitlines())} lines')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
